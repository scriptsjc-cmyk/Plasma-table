const BY_SHAPE = new Map();
for (const f of FAMILIES) for (const p of f.picks) if (!BY_SHAPE.has(p.shape)) BY_SHAPE.set(p.shape, f);
export function familyOfShape(id) { return BY_SHAPE.get(id) || null; }
export function familyById(id) { return FAMILIES.find((f) => f.id === id) || null; }
export function pickKey(p) { return p.p ? `${p.shape}:${JSON.stringify(p.p)}` : p.shape; }
